#!/usr/bin/env node
// Builds every platform's copy of the Nova64 cart kit from this folder.
//
//   node nova64-kit/build.mjs           write all outputs
//   node nova64-kit/build.mjs --check   exit 1 if any output is stale (used by tests)
//
// Outputs (mobile repos are siblings of WebMaigeXr and are skipped when absent):
//   WebMaigeXr/src/lib/nova64-kit.generated.ts
//   iOSMaigeXr/XRAiAssistant/Resources/playground-nova64.html        (inline <script>)
//   iOSMaigeXr/XRAiAssistant/Library3D/Nova64Templates.generated.swift
//   AndroidMaigeXr/app/src/main/assets/playground-nova64.html        (inline <script>)
//   AndroidMaigeXr/.../domain/models/Nova64TemplatesData.kt
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'
import vm from 'node:vm'

const HERE = dirname(fileURLToPath(import.meta.url))
const WEB = resolve(HERE, '..')
const MAIGE = resolve(WEB, '..')
const IOS = join(MAIGE, 'iOSMaigeXr')
const ANDROID = join(MAIGE, 'AndroidMaigeXr')
const check = process.argv.includes('--check')
const NOVA64_VERSION = '0.5.6'

const read = (p) => readFileSync(join(HERE, p), 'utf8')
const meta = JSON.parse(read('templates.json'))
const data = {
  version: NOVA64_VERSION,
  namespace: JSON.parse(read(`namespace-${NOVA64_VERSION}.json`)),
  promptTemplate: read('template-prompt.txt'),
  templates: meta.map((t) => ({ ...t, config: read(`configs/${t.id}.js`) })),
  engines: Object.fromEntries(readdirSync(join(HERE, 'engines')).map((f) => [f.replace(/\.js$/, ''), read(`engines/${f}`)]))
}
const kitSource = read('kit.src.js')
const PLACEHOLDER = '/*@NOVA64_KIT_DATA@*/ null'
if (!kitSource.includes(PLACEHOLDER)) throw new Error('kit.src.js lost its data placeholder')
// JSON is valid JS; escape </script> so the kit can be inlined into HTML.
const kit = kitSource.replace(PLACEHOLDER, JSON.stringify(data).replace(/<\/(script)/gi, '<\\/$1'))

// Load the built kit to compute test vectors for the native ports.
const sandbox = { module: { exports: {} } }
vm.runInNewContext(kit, sandbox)
const Kit = sandbox.module.exports
const VECTOR_MESSAGES = [
  ['Make a dungeon crawler about four monks in a flooded abbey', ''],
  ['make a neon cyberpunk dungeon crawler with hackers', ''],
  ['an endless runner through a lava mine', ''],
  ['synthwave lane runner on a violet grid', ''],
  ['an arena game where a firefly dodges spiders in a cave', ''],
  ['top-down arena: a spark collects energy cells while drones orbit', ''],
  ['a spinning cube with a glowing orb', ''],
  ['make the enemies faster and the walls green', 'fp-dungeon-wizardry'],
  ['change the title to SUNKEN ABBEY', 'lane-runner-grid'],
  ['make a new scene with a rotating planet', 'arena-dodger-cave'],
  ['build a dungeon crawler from scratch', ''],
  ['now make it a neon dungeon', 'fp-dungeon-wizardry'],
  ['make the dungeon spookier', 'fp-dungeon-odyssey'],
  ['a maze game set in an ice castle', ''],
  ['bullet hell in space', ''],
  ['A medieval RPG with a party of four', ''],
  ['a racing game with lanes of traffic', ''],
  ['a calm forest scene with fireflies', ''],
  ['different game: an arena dodger in a crystal cavern', 'lane-runner-corridor']
]
const vectors = VECTOR_MESSAGES.map(([message, current]) => ({
  message,
  current: current || null,
  expected: Kit.chooseTemplate(message, current ? `// NOVA64 TEMPLATE: ${current}\n` : '')
}))

const outputs = []
const banner = '// GENERATED by WebMaigeXr/nova64-kit/build.mjs from nova64-kit/. Do not edit by hand.'

// ---------------------------------------------------------------- web
outputs.push([join(WEB, 'src/lib/nova64-kit.generated.ts'), [
  '// @ts-nocheck',
  banner,
  'const __root: any = {};',
  kit.replace(/\s*if \(typeof module === 'object' && module\.exports\) module\.exports = api;/, '')
    .replace("})(typeof globalThis !== 'undefined' ? globalThis : this);", '})(__root);'),
  'export const Nova64KitRaw = __root.Nova64Kit',
  `export const NOVA64_KIT_TEST_VECTORS = ${JSON.stringify(vectors, null, 1)}`,
  ''
].join('\n')])

// ---------------------------------------------------------------- mobile playground pages
const BEGIN = '<!-- NOVA64-KIT:BEGIN (generated by WebMaigeXr/nova64-kit/build.mjs) -->'
const END = '<!-- NOVA64-KIT:END -->'
function inlineKit(path) {
  if (!existsSync(path)) return
  const html = readFileSync(path, 'utf8')
  const eol = html.includes('\r\n') ? '\r\n' : '\n'
  const block = `${BEGIN}\n    <script>\n${kit}\n    </script>\n    ${END}`.replace(/\r?\n/g, eol)
  let next
  if (html.includes(BEGIN)) {
    next = html.slice(0, html.indexOf(BEGIN)) + block + html.slice(html.indexOf(END) + END.length)
  } else {
    // First run: place the kit just before the page's main script.
    const tag = html.indexOf('<script>', html.indexOf('loader.js'))
    if (tag < 0) throw new Error(`No main <script> found in ${path}`)
    const lineStart = html.lastIndexOf('\n', tag) + 1
    next = html.slice(0, lineStart) + '    ' + block + eol + html.slice(lineStart)
  }
  outputs.push([path, next])
}
inlineKit(join(IOS, 'XRAiAssistant/Resources/playground-nova64.html'))
inlineKit(join(ANDROID, 'app/src/main/assets/playground-nova64.html'))

// ---------------------------------------------------------------- native data (prompt side only)
const swiftString = (s) => {
  let hashes = '#'
  while (s.includes(`"""${hashes}`) || s.includes(`"${hashes}`)) hashes += '#'
  return `${hashes}"""\n${s.replace(/\n$/, '')}\n"""${hashes}`
}
const nativeTemplates = data.templates.map(({ id, family, genre, style, description, guide, config }) =>
  ({ id, family, genre, style, description, guide, config }))
if (existsSync(join(IOS, 'XRAiAssistant'))) {
  outputs.push([join(IOS, 'XRAiAssistant/Library3D/Nova64Templates.generated.swift'), [
    banner,
    'import Foundation',
    '',
    'enum Nova64TemplateData {',
    `    static let nova64Version = "${NOVA64_VERSION}"`,
    `    static let promptTemplate = ${swiftString(data.promptTemplate)}`,
    '',
    '    static let templates: [Nova64TemplateInfo] = [',
    nativeTemplates.map((t) => [
      '        Nova64TemplateInfo(',
      `            id: "${t.id}", family: "${t.family}", genre: "${t.genre}", style: "${t.style}",`,
      `            description: ${swiftString(t.description)},`,
      `            guide: ${swiftString(t.guide)},`,
      `            config: ${swiftString(t.config)}`,
      '        )'
    ].join('\n')).join(',\n'),
    '    ]',
    '',
    '    /// chooseTemplate(message, currentTemplateId) -> expected id, computed by the JS kit.',
    '    static let testVectors: [(message: String, current: String?, expected: String?)] = [',
    vectors.map((v) => `        (${JSON.stringify(v.message)}, ${v.current ? JSON.stringify(v.current) : 'nil'}, ${v.expected ? JSON.stringify(v.expected) : 'nil'})`).join(',\n'),
    '    ]',
    '}',
    ''
  ].join('\n')])
}
const ktString = (s) => JSON.stringify(s).replace(/\$/g, '\\$')
const androidModels = join(ANDROID, 'app/src/main/java/com/xraiassistant/domain/models')
if (existsSync(androidModels)) {
  outputs.push([join(androidModels, 'Nova64TemplatesData.kt'), [
    banner,
    'package com.xraiassistant.domain.models',
    '',
    'object Nova64TemplatesData {',
    `    const val NOVA64_VERSION = "${NOVA64_VERSION}"`,
    `    val promptTemplate: String = ${ktString(data.promptTemplate)}`,
    '',
    '    val templates: List<Nova64TemplateInfo> = listOf(',
    nativeTemplates.map((t) => [
      '        Nova64TemplateInfo(',
      `            id = ${ktString(t.id)}, family = ${ktString(t.family)}, genre = ${ktString(t.genre)}, style = ${ktString(t.style)},`,
      `            description = ${ktString(t.description)},`,
      `            guide = ${ktString(t.guide)},`,
      `            config = ${ktString(t.config)}`,
      '        )'
    ].join('\n')).join(',\n'),
    '    )',
    '',
    '    /** chooseTemplate(message, currentTemplateId) -> expected id, computed by the JS kit. */',
    '    val testVectors: List<Triple<String, String?, String?>> = listOf(',
    vectors.map((v) => `        Triple(${ktString(v.message)}, ${v.current ? ktString(v.current) : 'null'}, ${v.expected ? ktString(v.expected) : 'null'})`).join(',\n'),
    '    )',
    '}',
    ''
  ].join('\n')])
}

let stale = 0
for (const [path, content] of outputs) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null
  if (current === content) continue
  stale++
  if (check) console.error(`stale: ${path}`)
  else { writeFileSync(path, content); console.log(`wrote ${path.replace(MAIGE + '/', '')}`) }
}
if (check && stale) { console.error('Run: node nova64-kit/build.mjs'); process.exit(1) }
if (!stale) console.log('Nova64 kit outputs are up to date.')
console.log('Template vectors:', vectors.map((v) => `${v.expected ?? '-'}`).join(' '))
